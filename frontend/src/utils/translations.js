/**
 * Get translated text
 * @param {string} section - Section name (e.g., 'weather', 'common')
 * @param {string} key - Translation key
 * @param {string} lang - Language code ('en', 'hi', 'mr')
 * @returns {string} - Translated text
 */
export const t = (section, key, lang = 'en') => {
  try {
    return translations[section]?.[key]?.[lang] || translations[section]?.[key]?.['en'] || key;
  } catch (e) {
    return key;
  }
};

export const tt = (section, key, lang = 'en', vars = {}) => {
  const text = t(section, key, lang);
  return Object.entries(vars).reduce(
    (acc, [name, value]) => acc.replaceAll(`{${name}}`, String(value)),
    text
  );
};

